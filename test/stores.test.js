'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { cacheKey, VerdictCache, OverrideStore, RecentStore, RECENT_TEXT } = require('../dist/lib/stores')

test('cache keys change with every part and keep parts apart', () => {
  const k = cacheKey('mail', 'text', 'fp', 'm1')
  assert.equal(k.length, 32)
  assert.equal(cacheKey('mail', 'text', 'fp', 'm1'), k)
  assert.notEqual(cacheKey('jira', 'text', 'fp', 'm1'), k)
  assert.notEqual(cacheKey('mail', 'text2', 'fp', 'm1'), k)
  assert.notEqual(cacheKey('mail', 'text', 'fp2', 'm1'), k)
  assert.notEqual(cacheKey('mail', 'text', 'fp', 'm2'), k)
  assert.notEqual(cacheKey('a', 'bc', 'fp', 'm'), cacheKey('ab', 'c', 'fp', 'm'))
})

test('the cache evicts the least recently used entry past its cap and round-trips', () => {
  const c = new VerdictCache(2)
  c.set('a', { p: 'fyi', s: 'mail' })
  c.set('b', { p: 'noise', s: 'jira' })
  c.get('a') // a is now the newest
  c.set('c', { p: 'urgent', s: 'mail' })
  assert.equal(c.get('b'), undefined)
  assert.ok(c.get('a') && c.get('c'))
  const back = VerdictCache.fromJSON(JSON.parse(JSON.stringify(c)), 2)
  assert.equal(back.size, 2)
  assert.equal(back.clear('mail'), 2)
  assert.equal(VerdictCache.fromJSON('junk').size, 0)
})

test('cache clear by source', () => {
  const c = new VerdictCache()
  c.set('a', { s: 'mail' })
  c.set('b', { s: 'jira' })
  assert.equal(c.clear('mail'), 1)
  assert.equal(c.size, 1)
  assert.equal(c.clear(), 1)
})

test('overrides are per source, capped, and round-trip per source', () => {
  const o = new OverrideStore(2)
  o.set('mail', '1', { priority: 'fyi' }, 't1')
  o.set('mail', '2', { priority: 'noise' }, 't2')
  o.set('mail', '3', { priority: 'urgent', kind: 'incident' }, 't3')
  o.set('jira', '1', { priority: 'action' }, 't4')
  assert.equal(o.get('mail', '1'), undefined)
  assert.equal(o.get('mail', '3').kind, 'incident')
  assert.equal(o.get('jira', '1').priority, 'action')
  assert.deepEqual(o.sources().sort(), ['jira', 'mail'])
  const o2 = new OverrideStore()
  o2.loadSource('mail', JSON.parse(JSON.stringify(o.sourceJSON('mail'))))
  assert.equal(o2.get('mail', '2').priority, 'noise')
  assert.equal(o2.clear('mail', '2'), true)
  assert.equal(o2.clear('mail', '2'), false)
})

test('recent keeps the newest per source, one row per id, text cut', () => {
  const r = new RecentStore(2)
  r.add('mail', { id: 'a', text: 'one', final: {} })
  r.add('mail', { id: 'b', text: 'two', final: {} })
  r.add('mail', { id: 'a', text: 'one again', final: {} })
  r.add('mail', { id: 'c', text: 'x'.repeat(RECENT_TEXT + 5), final: {} })
  assert.deepEqual(r.list('mail').map((x) => x.id), ['c', 'a'])
  assert.equal(r.find('mail', 'c').text.length, RECENT_TEXT)
  assert.equal(r.find('mail', 'c').truncated, true)
  assert.equal(r.find('mail', 'a').text, 'one again')
  const back = RecentStore.fromJSON(JSON.parse(JSON.stringify(r)))
  assert.deepEqual(back.sources(), ['mail'])
})
